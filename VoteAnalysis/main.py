"""
Main execution file

Program for simulating several N-versions of one module to test vote algorithms.
Experiment is carried out in Denis V. Gruzenkin's PhD thesis writing.
"""

import sys
from utils import input_num, check_is_none
from menu_enum import MenuItem
from controller import Controller


MODULE_INDEX_IS_NOT_DEFINDE_MESSAGE = 'Current module index is not defined yet. Please set it before using this menu item.'


def show_list(items: list, header='List items:'):
    print(header)
    for idx, item in enumerate(items, start=1):
        print(f'\n{idx}. {item}')
    print('\n')


def add_module(controller: Controller):
    default_name = f'Module {len(controller.modules_list) + 1}'
    name = input(f'Enter module name [{default_name}]: ') or default_name
    round_digits = input_num('Enter number of module digits round: ', (0, float('inf')), int, True)
    min_val = input_num('Enter minimal value that can be generated by versions: ', (0, float('inf')), float, False, round_digits)
    max_val = input_num('Enter maximal value that can be generated by versions: ', (0, float('inf')), float, False, round_digits)
    controller.add_module(name, round_digits, min_val, max_val)
    print(f'Module "{name}" was successfully added to the list!')


def save_module(controller: Controller):
    if controller.modules_list:
        if controller.current_module_index is None:
            show_list(controller.modules_list)
            controller.current_module_index = input_num('Enter module order number to save it: ', (-1, len(controller.modules_list))) - 1
        controller.save_module()
    else:
        print('Modules list is empty. There is no data to save!')


def set_current_module(modules_list: list):
    show_list(modules_list)
    return input_num('Enter module order number to select it as a current module: ', (-1, len(modules_list))) - 1


def generate_data(controller: Controller):
    exp_name = input('Enter experiment name: ')
    iterations = input_num('Enter iterations amount: ', (0, float('inf')))
    return controller.generate_experiment_data(exp_name, iterations)


def load_experiment_data(controller: Controller):
    if not controller.experiments_names_list:
        print('Loading experiments names from DB. This may take several minutes...')
        controller.get_experiment_data_from_db()
    show_list(controller.experiments_names_list, 'Experiments names:')
    exp_name_index = input_num('Choose experiment by order number to load its data: ', (-1, len(controller.experiments_names_list))) - 1
    try:
        controller.load_experiment_data(exp_name_index)
    except ValueError:
        print('There is no module name to load!')
    except Exception:
        print('Something went wrong!')


def save_vote_algorithms(controller: Controller):
    if controller.vote_algorithms_list:
        controller.save_vote_algorithms()
    else:
        print('There are no algorithms to save!')


def run_vote_algorithms(controller: Controller):
    if controller.modules_list[controller.current_module_index].global_results_lst:
        if controller.vote_algorithms_list:
            controller.run_vote_algorithms()
        else:
            print('There are no algorithms to run!')
    else:
        print('There is no experiment data list. Please generate it before running voting!')


def main():
    menu_dict = {
        'Add module to list': MenuItem.ADD_MODULE.value,
        'Load module list from DB': MenuItem.LOAD_MODULE_LIST.value,
        'Save module to DB': MenuItem.SAVE_MODULE.value,
        'Show modules list': MenuItem.SHOW_MODULES_LIST.value,
        'Set current module': MenuItem.SET_CURRENT_MODULE.value,
        'Show current module': MenuItem.SHOW_CURRENT_MODULE.value,
        'Add versions to module': MenuItem.ADD_VERSIONS.value,
        'Load module with versions from DB': MenuItem.LOAD_MODULE_WITH_VERSIONS.value,
        'Save module with versions to DB': MenuItem.SAVE_MODULE_WITH_VERSIONS.value,
        'Show module versions': MenuItem.SHOW_MODULE_VERSIONS.value,
        'Generate experiment data for module': MenuItem.GENERATE_EXPERIMENT_DATA.value,
        'Save module experiment data to DB': MenuItem.SAVE_EXPERIMENT_DATA.value,
        'Load module experiment data from DB': MenuItem.LOAD_EXPERIMENT_DATA.value,
        'Add vote algorithm': MenuItem.ADD_VOTE_ALGORITHM.value,
        'Load vote algorithms': MenuItem.LOAD_VOTE_ALGORITHMS.value,
        'Save vote algorithms list': MenuItem.SAVE_VOTE_ALGORITHMS.value,
        'Show vote algorithms': MenuItem.SHOW_VOTE_ALGORITHMS.value,
        'Run vote algorithms': MenuItem.RUN_VOTE_ALGORITHMS.value,
        'Make experiment analysis': MenuItem.MAKE_EXPERIMENT_ANALYSIS.value,
        'Exit': MenuItem.EXIT.value
    }
    menu_str = '\nPlease choose a menu item:\n' + '\n'.join([f'{v}. {k}' for k, v in menu_dict.items()]) + '\n'

    controller = Controller()

    while (user_choice := input_num(menu_str, (0, 19), int, True, 0)) != menu_dict['Exit']:
        match user_choice:
            case MenuItem.ADD_MODULE.value:
                add_module(controller)
            case MenuItem.LOAD_MODULE_LIST.value:
                controller.load_module()
            case MenuItem.SAVE_MODULE.value:
                save_module(controller)
            case MenuItem.SHOW_MODULES_LIST.value:
                show_list(controller.modules_list)
            case MenuItem.SET_CURRENT_MODULE.value:
                controller.current_module_index = set_current_module(controller.modules_list)
                print(f'Current module index is {controller.current_module_index + 1}')
            case MenuItem.SHOW_CURRENT_MODULE.value:
                if check_is_none(controller.current_module_index, MODULE_INDEX_IS_NOT_DEFINDE_MESSAGE):
                    print(f'{controller.current_module_index + 1}. {controller.modules_list[controller.current_module_index]}')
            case MenuItem.ADD_VERSIONS.value:
                if check_is_none(controller.current_module_index, MODULE_INDEX_IS_NOT_DEFINDE_MESSAGE):
                    controller.add_versions()
            case MenuItem.LOAD_MODULE_WITH_VERSIONS.value:
                controller.load_module_with_versions()
            case MenuItem.SAVE_MODULE_WITH_VERSIONS.value:
                if check_is_none(controller.current_module_index, MODULE_INDEX_IS_NOT_DEFINDE_MESSAGE):
                    controller.save_module_with_versions()
            case MenuItem.SHOW_MODULE_VERSIONS.value:
                if check_is_none(controller.current_module_index, MODULE_INDEX_IS_NOT_DEFINDE_MESSAGE):
                    show_list(controller.modules_list[controller.current_module_index].versions_list, 
                              f'Versions of module {controller.current_module_index + 1}')
            case MenuItem.GENERATE_EXPERIMENT_DATA.value:
                if check_is_none(controller.current_module_index, MODULE_INDEX_IS_NOT_DEFINDE_MESSAGE):
                    print(generate_data(controller))
            case MenuItem.SAVE_EXPERIMENT_DATA.value:
                if check_is_none(controller.current_module_index, MODULE_INDEX_IS_NOT_DEFINDE_MESSAGE):
                    controller.save_experiment_data()
            case MenuItem.LOAD_EXPERIMENT_DATA.value:
                if check_is_none(controller.current_module_index, MODULE_INDEX_IS_NOT_DEFINDE_MESSAGE):
                    load_experiment_data(controller)
            case MenuItem.ADD_VOTE_ALGORITHM.value:
                algorithm_name = input('Enter vote algorithm name: ')
                module_name = input('Enter Python module name (it should be located in VoteAlgorithms package): ')
                function_name = input('Enter vote function name in module: ')
                controller.add_vote_algorithm(algorithm_name, function_name, module_name)
            case MenuItem.LOAD_VOTE_ALGORITHMS.value:
                if input('Unsaved algorithms will be lost! Are you sure (Y - yes; any key - no)? ').upper() == 'Y':
                    controller.load_vote_algorithms()
            case MenuItem.SAVE_VOTE_ALGORITHMS.value:
                save_vote_algorithms(controller)
            case MenuItem.SHOW_VOTE_ALGORITHMS.value:
                if controller.vote_algorithms_list:
                    for algorithm in controller.vote_algorithms_list:
                        print(algorithm)
                else:
                    print('There are no algorithms to show!')
            case MenuItem.RUN_VOTE_ALGORITHMS.value:
                if check_is_none(controller.current_module_index, MODULE_INDEX_IS_NOT_DEFINDE_MESSAGE):
                    run_vote_algorithms(controller)
            case MenuItem.MAKE_EXPERIMENT_ANALYSIS.value:
                pass

if __name__ == '__main__':
    sys.exit(main())
